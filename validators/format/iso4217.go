// ISO4217 要求现行 ISO 4217 字母代码，大小写不敏感。
func ISO4217[T ~string]() hvalid.ValidatorFunc[T] {
	return func(value T) error {
		if _, ok := iso4217[strings.ToUpper(string(value))]; !ok {
			return errors.New("must be an ISO 4217 code")
		}
		return nil
	}
}
